// Program Start Block
nxcGenerator.forBlock['nxt_start'] = function (block, generator) {
  return '';
};

// Play Tone
nxcGenerator.forBlock['nxt_play_tone'] = function (block, generator) {
  const freq = generator.valueToCode(block, 'FREQUENCY', Order.NONE) || '440';
  const dur = generator.valueToCode(block, 'DURATION', Order.NONE) || '500';
  return `PlayTone(${freq}, ${dur});\nWait(${dur});\n`;
};

// Set Motor Power
nxcGenerator.forBlock['nxt_motor_power'] = function (block, generator) {
  const port = getPortConst(block.getFieldValue('PORT'));
  const power = generator.valueToCode(block, 'POWER', Order.NONE) || '0';
  return `SetMotorPower(${port}, ${power});\n`;
};

// Stop Motor
nxcGenerator.forBlock['nxt_motor_stop'] = function (block, generator) {
  const port = getPortConst(block.getFieldValue('PORT'));
  const mode = block.getFieldValue('MODE') || 'BRAKE';
  if (mode === 'BRAKE') {
    return `Off(${port});\n`;
  } else {
    return `Float(${port});\n`;
  }
};

