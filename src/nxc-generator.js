// NXC (Not eXactly C) Code Generator for LEGO Mindstorms NXT
// Generates standard C-like NXC code compilable by NBC (Next Byte Codes) compiler
import * as Blockly from 'blockly';

export const nxcGenerator = new Blockly.Generator('NXC');

// NXC Precedence Orders
export const Order = {
  ATOMIC: 0,
  MEMBER: 1,
  FUNCTION_CALL: 2,
  INCREMENT: 3,
  LOGICAL_NOT: 4,
  UNARY: 5,
  MULTIPLICATIVE: 6,
  ADDITIVE: 7,
  RELATIONAL: 8,
  EQUALITY: 9,
  LOGICAL_AND: 10,
  LOGICAL_OR: 11,
  ASSIGNMENT: 12,
  NONE: 99
};

function getPortConst(portStr) {
  switch (String(portStr).toUpperCase()) {
    case 'A': return 'OUT_A';
    case 'B': return 'OUT_B';
    case 'C': return 'OUT_C';
    case 'ALL': return 'OUT_ABC';
    default: return 'OUT_A';
  }
}

function getSensorPortConst(idxStr) {
  switch (String(idxStr)) {
    case '0': return 'IN_1';
    case '1': return 'IN_2';
    case '2': return 'IN_3';
    case '3': return 'IN_4';
    default: return 'IN_1';
  }
}

function sanitizeNxcIdent(name) {
  if (!name) return 'item';
  let clean = String(name).replace(/[^a-zA-Z0-9_]/g, '_');
  if (/^[0-9]/.test(clean)) {
    clean = '_' + clean;
  }
  return clean || 'item';
}

// Initializer runs before workspaceToCode
nxcGenerator.init = function (workspace) {
  this.usedSensors = new Set();
  this.variables = [];
  this.definitions_ = Object.create(null);

  if (!this.nameDB_) {
    this.nameDB_ = new Blockly.Names(this.RESERVED_WORDS_ || '');
  } else {
    this.nameDB_.reset();
  }
  this.nameDB_.setVariableMap(workspace.getVariableMap());

  const allVars = Blockly.Variables.allUsedVarModels(workspace) || [];
  for (const v of allVars) {
    const varName = sanitizeNxcIdent(this.getVariableName(v.getId()));
    this.variables.push(varName);
  }
};

// Scrubber to link consecutive blocks
nxcGenerator.scrub_ = function (block, code, thisOnly) {
  const nextBlock = block.nextConnection && block.nextConnection.targetBlock();
  if (nextBlock && !thisOnly) {
    return code + this.blockToCode(nextBlock);
  }
  return code;
};

// Workspace to code with start block scoping (only compiles blocks connected to start block if present)
nxcGenerator.workspaceToCode = function (workspace) {
  if (!workspace) return '';
  this.init(workspace);
  const topBlocks = workspace.getTopBlocks(true);

  // 1. Process all procedure definitions first so they populate this.definitions_
  const procBlocks = topBlocks.filter(b => b.type === 'procedures_defnoreturn' || b.type === 'procedures_defreturn');
  for (const block of procBlocks) {
    this.blockToCode(block);
  }

  // 2. Process main execution flow from start block (or fallback to non-procedure top blocks)
  const startBlocks = topBlocks.filter(b => b.type === 'nxt_start');
  const blocksToProcess = startBlocks.length > 0
    ? startBlocks
    : topBlocks.filter(b => b.type !== 'procedures_defnoreturn' && b.type !== 'procedures_defreturn');

  const blocksCode = [];
  for (const block of blocksToProcess) {
    const line = this.blockToCode(block);
    if (line) {
      blocksCode.push(line);
    }
  }
  return this.finish(blocksCode.join('\n'));
};

// Finish wraps statements into task main(), global variables, and helper functions
nxcGenerator.finish = function (code) {
  let sensorInits = '';
  for (const s of (this.usedSensors || [])) {
    sensorInits += `  ${s}\n`;
  }

  let varDecls = '';
  for (const v of (this.variables || [])) {
    varDecls += `float ${v} = 0;\n`;
  }

  let procDefs = '';
  for (const d of Object.values(this.definitions_ || {})) {
    procDefs += `${d}\n`;
  }

  const indentedCode = code ? this.prefixLines(code, '  ') : '  // Empty program\n';

  return `// Generated by NXT-Scratch Visual IDE for LEGO Mindstorms NXT\n` +
    `// Language: NXC (Not eXactly C)\n\n` +
    `inline void SetMotorPower(byte out, int pwr) {\n` +
    `  if (pwr >= 0) {\n` +
    `    OnFwd(out, pwr);\n` +
    `  } else {\n` +
    `    OnRev(out, -pwr);\n` +
    `  }\n` +
    `}\n\n` +
    `// Math & Trigonometry Helpers\n` +
    `inline float NxtSin(float deg) {\n` +
    `  int d = deg;\n` +
    `  return glSin32768(d) / 32768.0;\n` +
    `}\n\n` +
    `inline float NxtCos(float deg) {\n` +
    `  int d = deg;\n` +
    `  return glCos32768(d) / 32768.0;\n` +
    `}\n\n` +
    `inline float NxtTan(float deg) {\n` +
    `  float c = NxtCos(deg);\n` +
    `  if (abs(c) < 0.0001) return 999999.0;\n` +
    `  return NxtSin(deg) / c;\n` +
    `}\n\n` +
    `inline float NxtAtan(float x) {\n` +
    `  float rad = x / (1.0 + 0.28086 * x * x);\n` +
    `  return rad * (180.0 / 3.14159265);\n` +
    `}\n\n` +
    `inline float NxtAsin(float x) {\n` +
    `  if (x >= 1.0) return 90.0;\n` +
    `  if (x <= -1.0) return -90.0;\n` +
    `  float denom = sqrt(1.0 - x * x);\n` +
    `  if (denom < 0.0001) return x > 0 ? 90.0 : -90.0;\n` +
    `  return NxtAtan(x / denom);\n` +
    `}\n\n` +
    `inline float NxtAcos(float x) {\n` +
    `  return 90.0 - NxtAsin(x);\n` +
    `}\n\n` +
    `inline float NxtMod(float a, float b) {\n` +
    `  int ia = a;\n` +
    `  int ib = b;\n` +
    `  if (ib == 0) return 0;\n` +
    `  return ia % ib;\n` +
    `}\n\n` +
    `inline float NxtRound(float a) {\n` +
    `  int r;\n` +
    `  if (a >= 0) r = a + 0.5;\n` +
    `  else r = a - 0.5;\n` +
    `  return r;\n` +
    `}\n\n` +
    `inline float NxtFloor(float a) {\n` +
    `  int r = a;\n` +
    `  if (a < 0 && a != r) r = r - 1;\n` +
    `  return r;\n` +
    `}\n\n` +
    `inline float NxtCeil(float a) {\n` +
    `  int r = a;\n` +
    `  if (a > 0 && a != r) r = r + 1;\n` +
    `  return r;\n` +
    `}\n\n` +
    `float NxtPow(float base, float exp) {\n` +
    `  int ie = exp;\n` +
    `  float res = 1.0;\n` +
    `  int i;\n` +
    `  if (ie >= 0) {\n` +
    `    for (i = 0; i < ie; i++) res *= base;\n` +
    `  } else {\n` +
    `    for (i = 0; i < -ie; i++) res /= base;\n` +
    `  }\n` +
    `  return res;\n` +
    `}\n\n` +
    (varDecls ? `// Global Variables\n${varDecls}\n` : '') +
    (procDefs ? `// User Procedures / Functions\n${procDefs}\n` : '') +
    `task main() {\n` +
    (sensorInits ? `  // Sensor Configurations\n${sensorInits}\n` : '') +
    `${indentedCode}` +
    `  StopAllTasks();\n` +
    `}\n`;
};

