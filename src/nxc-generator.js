// --- Procedure / Function Blocks for NXC ---

nxcGenerator.forBlock['procedures_defnoreturn'] = function (block, generator) {
  const funcName = sanitizeNxcIdent(block.getFieldValue('NAME'));
  const branch = generator.statementToCode(block, 'STACK');
  const args = [];
  const variables = block.getVars ? block.getVars() : [];
  for (let i = 0; i < variables.length; i++) {
    const varName = sanitizeNxcIdent(generator.getVariableName(variables[i]));
    args.push(`float ${varName}`);
  }
  const code = `void ${funcName}(${args.join(', ')}) {\n${branch}}\n`;
  generator.definitions_['proc_' + funcName] = code;
  return null;
};

nxcGenerator.forBlock['procedures_defreturn'] = function (block, generator) {
  const funcName = sanitizeNxcIdent(block.getFieldValue('NAME'));
  const branch = generator.statementToCode(block, 'STACK');
  const retVal = generator.valueToCode(block, 'RETURN', Order.NONE) || '0';
  const args = [];
  const variables = block.getVars ? block.getVars() : [];
  for (let i = 0; i < variables.length; i++) {
    const varName = sanitizeNxcIdent(generator.getVariableName(variables[i]));
    args.push(`float ${varName}`);
  }
  const code = `float ${funcName}(${args.join(', ')}) {\n${branch}  return ${retVal};\n}\n`;
  generator.definitions_['proc_' + funcName] = code;
  return null;
};

nxcGenerator.forBlock['procedures_callnoreturn'] = function (block, generator) {
  const funcName = sanitizeNxcIdent(block.getFieldValue('NAME'));
  const args = [];
  const variables = block.getVars ? block.getVars() : [];
  for (let i = 0; i < variables.length; i++) {
    args.push(generator.valueToCode(block, 'ARG' + i, Order.NONE) || '0');
  }
  return `${funcName}(${args.join(', ')});\n`;
};

nxcGenerator.forBlock['procedures_callreturn'] = function (block, generator) {
  const funcName = sanitizeNxcIdent(block.getFieldValue('NAME'));
  const args = [];
  const variables = block.getVars ? block.getVars() : [];
  for (let i = 0; i < variables.length; i++) {
    args.push(generator.valueToCode(block, 'ARG' + i, Order.NONE) || '0');
  }
  return [`${funcName}(${args.join(', ')})`, Order.FUNCTION_CALL];
};

nxcGenerator.forBlock['procedures_ifreturn'] = function (block, generator) {
  const cond = generator.valueToCode(block, 'CONDITION', Order.NONE) || 'false';
  let ret = '';
  if (block.hasReturnValue_ && block.getInput('VALUE')) {
    const val = generator.valueToCode(block, 'VALUE', Order.NONE) || '0';
    ret = ` return ${val};`;
  } else {
    ret = ' return;';
  }
  return `if (${cond}) {${ret} }\n`;
};

// --- Text & Display Generators for NXC ---

nxcGenerator.forBlock['text'] = function (block) {
  const textVal = block.getFieldValue('TEXT') || '';
  return [JSON.stringify(textVal), Order.ATOMIC];
};

nxcGenerator.forBlock['text_join'] = function (block, generator) {
  const count = block.itemCount_ !== undefined ? block.itemCount_ : 2;
  if (count === 0) {
    return ['""', Order.ATOMIC];
  }
  const elements = [];
  for (let i = 0; i < count; i++) {
    const raw = generator.valueToCode(block, 'ADD' + i, Order.NONE) || '""';
    const isStr = raw.startsWith('"') || raw.startsWith('StrCat') || raw.startsWith('NumToStr');
    elements.push(isStr ? raw : `NumToStr(${raw})`);
  }
  if (elements.length === 1) {
    return [elements[0], Order.ATOMIC];
  }
  return [`StrCat(${elements.join(', ')})`, Order.FUNCTION_CALL];
};

nxcGenerator.forBlock['nxt_display_text'] = function (block, generator) {
  const text = generator.valueToCode(block, 'TEXT', Order.NONE) || '""';
  const line = block.getFieldValue('LINE') || 'LCD_LINE1';
  const isString = text.startsWith('"') || text.startsWith('StrCat') || text.startsWith('NumToStr');
  const textArg = isString ? text : `NumToStr(${text})`;
  return `TextOut(0, ${line}, ${textArg});\n`;
};

nxcGenerator.forBlock['nxt_display_number'] = function (block, generator) {
  const num = generator.valueToCode(block, 'NUM', Order.NONE) || '0';
  const line = block.getFieldValue('LINE') || 'LCD_LINE1';
  return `NumOut(0, ${line}, ${num});\n`;
};

